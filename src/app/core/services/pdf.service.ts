import { Injectable, inject } from '@angular/core';
import { AuthService } from '../auth/auth.service';
import type { CustomerLedger, Report, Sale } from '../models/domain.models';
import { formatIstDate } from '../../shared/pipes/ist-date.pipe';
import { formatQty, rsText } from '../utils/format';

type JsPdf = import('jspdf').jsPDF;

const BRAND: [number, number, number] = [30, 95, 168];

/**
 * PDF generation in the browser. jsPDF + autotable are loaded lazily so they
 * don't weigh on the initial bundle. Built-in PDF fonts have no ₹ glyph or
 * Devanagari, so amounts are written as "Rs." and names as typed.
 */
@Injectable({ providedIn: 'root' })
export class PdfService {
  private readonly auth = inject(AuthService);

  private async create(): Promise<{ doc: JsPdf; autoTable: typeof import('jspdf-autotable').default }> {
    const [{ jsPDF }, autoTable] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
    return { doc: new jsPDF({ unit: 'pt', format: 'a4' }), autoTable: autoTable.default };
  }

  private header(doc: JsPdf, title: string, subtitle?: string): number {
    const shop = this.auth.user();
    const w = doc.internal.pageSize.getWidth();
    doc.setFillColor(...BRAND);
    doc.rect(0, 0, w, 70, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.text(shop?.shopName ?? 'DukaanSathi', 40, 32);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.text([shop?.shopAddress, shop?.phone ? `Ph: ${shop.phone}` : '', shop?.gstNumber ? `GSTIN: ${shop.gstNumber}` : ''].filter(Boolean).join('  |  '), 40, 52);
    doc.setTextColor(20, 20, 20);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text(title, 40, 100);
    if (subtitle) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(90, 90, 90);
      doc.text(subtitle, 40, 116);
    }
    return subtitle ? 132 : 116;
  }

  private footer(doc: JsPdf): void {
    const pages = doc.getNumberOfPages();
    const h = doc.internal.pageSize.getHeight();
    const w = doc.internal.pageSize.getWidth();
    for (let i = 1; i <= pages; i++) {
      doc.setPage(i);
      doc.setFontSize(8);
      doc.setTextColor(130, 130, 130);
      doc.text(`Generated by DukaanSathi on ${formatIstDate(new Date(), true)}`, 40, h - 20);
      doc.text(`Page ${i} of ${pages}`, w - 40, h - 20, { align: 'right' });
    }
  }

  /** `upi`: adds a "Pay via UPI" QR + link under the balance (only when something is due). */
  async customerStatement(ledger: CustomerLedger, from?: string, to?: string, upi?: { link: string; qr: string; vpa: string }): Promise<File> {
    const { doc, autoTable } = await this.create();
    const c = ledger.customer;
    const range = from || to ? `Period: ${from ? formatIstDate(from) : 'start'} to ${to ? formatIstDate(to) : 'today'}` : 'Full account statement';
    const y = this.header(doc, `Account statement - ${c.name}`, `${c.phone ? `Ph: ${c.phone}  |  ` : ''}${range}`);

    const body: string[][] = [];
    if (ledger.openingBalance) body.push(['', 'Opening balance', '', '', rsText(ledger.openingBalance)]);
    for (const e of ledger.entries) {
      const desc = [e.note, e.items.length ? e.items.map((i) => `${i.name} x${formatQty(i.qty)}`).join(', ') : ''].filter(Boolean).join(' - ');
      body.push([
        formatIstDate(e.date),
        desc || (e.type === 'credit' ? 'Udhaar (credit)' : `Payment${e.mode ? ` (${e.mode})` : ''}`),
        e.credit ? rsText(e.credit) : '',
        e.payment ? rsText(e.payment) : '',
        rsText(e.balance),
      ]);
    }
    autoTable(doc, {
      startY: y,
      head: [['Date', 'Description', 'Udhaar', 'Payment', 'Balance']],
      body,
      styles: { fontSize: 9, cellPadding: 5 },
      headStyles: { fillColor: BRAND },
      columnStyles: { 0: { cellWidth: 70 }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' } },
    });
    const endY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 24;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(ledger.closingBalance > 0 ? 198 : 21, ledger.closingBalance > 0 ? 40 : 128, ledger.closingBalance > 0 ? 40 : 61);
    doc.text(
      ledger.closingBalance > 0 ? `Balance due: ${rsText(ledger.closingBalance)}` : ledger.closingBalance < 0 ? `Advance: ${rsText(-ledger.closingBalance)}` : 'No balance due',
      40,
      endY,
    );
    if (upi && ledger.closingBalance > 0) {
      const h = doc.internal.pageSize.getHeight();
      let top = endY + 16;
      if (top + 130 > h - 40) {
        doc.addPage();
        top = 50;
      }
      doc.addImage(upi.qr, 'PNG', 40, top, 110, 110);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(30, 30, 30);
      doc.text('Pay via UPI', 165, top + 18);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(90, 90, 90);
      doc.text(`Scan with any UPI app or pay to ${upi.vpa}`, 165, top + 36);
      doc.textWithLink('Tap here to pay (UPI link)', 165, top + 54, { url: upi.link });
    }
    this.footer(doc);
    const name = `statement-${c.name.replace(/\W+/g, '-').toLowerCase()}.pdf`;
    return new File([doc.output('blob')], name, { type: 'application/pdf' });
  }

  async bill(sale: Sale): Promise<File> {
    const { doc, autoTable } = await this.create();
    const customer = sale.customer?.name || sale.customerName || 'Walk-in customer';
    const y = this.header(doc, `Bill #${sale.billNumber}`, `${formatIstDate(sale.date, true)}  |  ${customer}${sale.customer?.phone ? ` (${sale.customer.phone})` : ''}`);
    autoTable(doc, {
      startY: y,
      head: [['#', 'Item', 'Qty', 'Rate', 'Amount']],
      body: sale.items.map((i, n) => [String(n + 1), i.name, formatQty(i.qty, i.unit), rsText(i.rate), rsText(i.total)]),
      styles: { fontSize: 10, cellPadding: 6 },
      headStyles: { fillColor: BRAND },
      columnStyles: { 0: { cellWidth: 26 }, 2: { halign: 'right' }, 3: { halign: 'right' }, 4: { halign: 'right' } },
      foot: [
        ['', '', '', 'Subtotal', rsText(sale.subtotal)],
        ...(sale.discount ? [['', '', '', 'Discount', `- ${rsText(sale.discount)}`]] : []),
        ['', '', '', 'Total', rsText(sale.totalAmount)],
        ['', '', '', 'Paid', rsText(sale.paidAmount)],
        ...(sale.creditAmount ? [['', '', '', 'Udhaar', rsText(sale.creditAmount)]] : []),
      ],
      footStyles: { fillColor: [245, 247, 250], textColor: 20, halign: 'right', fontStyle: 'bold' },
    });
    const endY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 26;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(90, 90, 90);
    doc.text(`Payment: ${sale.paymentMode.toUpperCase()}`, 40, endY);
    doc.text('Thank you! Visit again.', 40, endY + 16);
    this.footer(doc);
    return new File([doc.output('blob')], `bill-${sale.billNumber}.pdf`, { type: 'application/pdf' });
  }

  async report(report: Report): Promise<File> {
    const { doc, autoTable } = await this.create();
    const range = report.from || report.to ? `${report.from ? formatIstDate(report.from) : ''} - ${report.to ? formatIstDate(report.to) : formatIstDate(new Date())}` : `As of ${formatIstDate(new Date())}`;
    const y = this.header(doc, report.title, range);
    const fmt = (type: string, v: unknown) =>
      type === 'money' ? rsText(Number(v) || 0) : type === 'date' ? formatIstDate(String(v)) : v === undefined || v === null ? '' : String(v);
    autoTable(doc, {
      startY: y,
      head: [report.columns.map((c) => c.label)],
      body: report.rows.map((r) => report.columns.map((c) => fmt(c.type, r[c.key]))),
      foot: [report.columns.map((c, i) => (i === 0 ? 'Total' : c.key in report.totals ? fmt(c.type, report.totals[c.key]) : ''))],
      styles: { fontSize: 8, cellPadding: 4 },
      headStyles: { fillColor: BRAND },
      footStyles: { fillColor: [245, 247, 250], textColor: 20, fontStyle: 'bold' },
      columnStyles: Object.fromEntries(report.columns.map((c, i) => [i, { halign: c.type === 'money' || c.type === 'number' ? 'right' : 'left' }])),
    });
    this.footer(doc);
    return new File([doc.output('blob')], `${report.title.toLowerCase().replace(/\W+/g, '-')}.pdf`, { type: 'application/pdf' });
  }
}
